/// Files of the start-game pack in the original manager's order. The order is
/// already ascending, which is how the game expects pack indexes to be sorted.
pub fn start_pack_files(options: &Options) -> Vec<(&'static str, Vec<u8>)> {
    let mut files = Vec::new();
    if options.skip_intro_movies {
        files.extend(
            INTRO_MOVIES
                .iter()
                .map(|path| (*path, EMPTY_MOVIE.to_vec())),
        );
    }
    if options.script_logging {
        files.push((SCRIPT_LOGGING, vec![0]));
    }
    if options.auto_start_custom_battle {
        files.push((
            AUTO_START_CUSTOM_BATTLE,
            AUTO_START_CUSTOM_BATTLE_SCRIPT.as_bytes().to_vec(),
        ));
    }
    files
}
