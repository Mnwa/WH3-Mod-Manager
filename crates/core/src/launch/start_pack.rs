//! Contents of the generated start-game pack, ported from the original manager
//! (`writeStartGamePack` and its `create*Data` helpers).

/// Name of the generated pack. The leading `!` characters keep the original
/// manager's name so saves and logs from both managers refer to the same file.
pub const TEMP_PACK: &str = "!!!!out.pack";

/// Start-game switches that are applied through the generated pack.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Options {
    pub skip_intro_movies: bool,
    pub script_logging: bool,
    pub auto_start_custom_battle: bool,
    /// Let every custom-battle unit be picked as a general (the original's
    /// "Make units generals"); the table is built from the enabled mods at launch.
    pub make_units_generals: bool,
}

impl Options {
    /// Whether the generated pack has to be written and loaded.
    pub fn any(&self) -> bool {
        self.skip_intro_movies
            || self.script_logging
            || self.auto_start_custom_battle
            || self.make_units_generals
    }
}

